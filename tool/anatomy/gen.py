"""Генератор анатомической фигуры LIFE OS (собственный рисунок; стоковые изображения не используются).

Запуск:
  python3 tool/anatomy/gen.py preview.html                      — SVG-превью (спереди и сзади)
  python3 tool/anatomy/gen.py - --dart lib/ui/painters/anatomy_geometry.dart

Как устроено: каждая фигура — список точек ЛЕВОЙ (для зрителя) половины тела, правая получается зеркально.
Точка (x, y) — гладкая, (x, y, 'c') — острый угол (концы мышц-веретён, вырезы между пальцами).
Контур сглаживается сплайном Катмулла — Рома и переводится в кубические кривые Безье.
База 370×780, ось симметрии x = 185. Пропорции: рост 8 голов, плечи ≈ 2,2 высоты головы.
"""
import sys

W, H, CX = 370, 780, 185


def smooth(pts, k=0.9):
    """Замкнутый контур через точки; у точек с меткой 'c' касательная ломается (острый угол)."""
    n = len(pts)
    P = [(p[0], p[1]) for p in pts]
    C = [len(p) > 2 for p in pts]
    d = f"M{P[0][0]:.1f},{P[0][1]:.1f}"
    for i in range(n):
        p0, p1, p2, p3 = P[(i - 1) % n], P[i], P[(i + 1) % n], P[(i + 2) % n]
        t1 = (p2[0] - p1[0], p2[1] - p1[1]) if C[i] else ((p2[0] - p0[0]) / 2, (p2[1] - p0[1]) / 2)
        t2 = (p2[0] - p1[0], p2[1] - p1[1]) if C[(i + 1) % n] else ((p3[0] - p1[0]) / 2, (p3[1] - p1[1]) / 2)
        c1 = (p1[0] + t1[0] * k / 3, p1[1] + t1[1] * k / 3)
        c2 = (p2[0] - t2[0] * k / 3, p2[1] - t2[1] * k / 3)
        d += f" C{c1[0]:.1f},{c1[1]:.1f} {c2[0]:.1f},{c2[1]:.1f} {p2[0]:.1f},{p2[1]:.1f}"
    return d + " Z"


def mirror(pts):
    return [((2 * CX - p[0]), p[1]) + tuple(p[2:]) for p in reversed(pts)]


def both(pts):
    """Фигура левой половины и её зеркальная пара."""
    return [smooth(pts), smooth(mirror(pts))]


def sym(left):
    """Симметричная фигура: левая половина от верхней точки на оси до нижней точки на оси."""
    return [smooth(left + mirror(left))]


